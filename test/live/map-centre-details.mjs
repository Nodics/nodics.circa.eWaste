import assert from 'node:assert/strict';
import { chromium } from '@playwright/test';

const browser = await chromium.launch();
const context = await browser.newContext({ viewport: { width: 1440, height: 1000 } });
const page = await context.newPage();
const errors = [];
page.on('pageerror', error => errors.push(error.message));
try {
  await page.goto(process.env.CIRCA_URL || 'http://localhost:3600');
  await page.getByRole('button', { name: 'Expand map', exact: true }).click();
  const pins = page.locator('.location-marker');
  await pins.first().waitFor();
  const name = await pins.first().getAttribute('title');
  await pins.first().click({ force: true });
  const popup = page.getByRole('dialog', { name: 'Collection centre details', exact: true });
  await popup.waitFor();
  await page.waitForTimeout(900);
  assert.equal(await popup.count(), 1);
  await popup.getByText(name, { exact: true }).waitFor();
  await popup.getByText('Drop off approved e-waste here for verified recycling.', { exact: true }).waitFor();
  await popup.getByRole('button', { name: 'Directions', exact: true }).waitFor();
  const next = page.locator('.centre-row').nth(1);
  await next.click();
  await page.waitForTimeout(900);
  assert.equal(await popup.count(), 1);
  await popup.getByText('Averda Recycling Center - Nadd Al Hamar', { exact: true }).waitFor();
  if (process.env.CIRCA_MAP_SCREENSHOT) await page.screenshot({ path: process.env.CIRCA_MAP_SCREENSHOT });
  await popup.getByRole('button', { name: 'Close collection centre popup' }).click();
  assert.equal(await popup.count(), 0);
  await next.click();
  await popup.waitFor();
  await page.keyboard.press('Escape');
  assert.equal(await popup.count(), 0);
  await page.getByRole('button', { name: 'Collapse map', exact: true }).waitFor();
  await next.click();
  await popup.waitFor();
  await page.getByRole('button', { name: 'Repair', exact: true }).click();
  assert.equal(await popup.count(), 0, 'Filtering out a centre closes its popup');
  await page.getByRole('button', { name: 'Repair', exact: true }).click();
  await next.click();
  await popup.waitFor();
  await page.setViewportSize({ width: 390, height: 844 });
  await page.waitForTimeout(900);
  const rect = await popup.boundingBox();
  assert(rect && rect.x >= 0 && rect.x + rect.width <= 390, 'Popup fits on mobile');
  await popup.getByRole('button', { name: 'Directions', exact: true }).scrollIntoViewIfNeeded();
  if (process.env.CIRCA_MAP_MOBILE_SCREENSHOT) await page.screenshot({ path: process.env.CIRCA_MAP_MOBILE_SCREENSHOT });
  await page.evaluate(() => { window.open = url => { document.body.dataset.testDirectionsUrl = String(url); return null; }; });
  await popup.getByRole('button', { name: 'Directions', exact: true }).click();
  const directionsUrl = await page.locator('body').getAttribute('data-test-directions-url');
  assert.match(directionsUrl, /destination=25\.2010045,55\.3808318/);
  assert.deepEqual(errors, []);
  console.log('Centre details verified: pin/list clicks, shared Axis content, close/reopen, Escape, filters, mobile and directions coordinates.');
} catch (error) {
  await page.screenshot({ path: '/tmp/circa-map-shared/popup-failure.png' });
  console.error(error);
  process.exitCode = 1;
} finally { await browser.close(); }
